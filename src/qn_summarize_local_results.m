function summary = qn_summarize_local_results(results_dir,expected_worker_count,face_subdivisions)
% Summarize the saved output for Algorithm 1 and Table 3.
% The standard cover has 8*12^3 top-level direction boxes. Pass the
% expected worker count explicitly when auditing a newly generated run.

if nargin<1 || isempty(results_dir)
    root=fileparts(fileparts(mfilename('fullpath')));
    results_dir=fullfile(root,'results','local');
end
if nargin<3 || isempty(face_subdivisions), face_subdivisions=12; end
assert(isnumeric(face_subdivisions) && isscalar(face_subdivisions) && ...
    isfinite(face_subdivisions) && face_subdivisions>=1 && ...
    face_subdivisions==floor(face_subdivisions), ...
    'face_subdivisions must be a positive integer.');
expected_top_level_boxes=8*face_subdivisions^3;
files=dir(fullfile(results_dir,'res_*.csv'));
assert(~isempty(files),'No local result files found.');
T=table();
for k=1:numel(files)
    Tk=readtable(fullfile(files(k).folder,files(k).name));
    if k==1, T=Tk; else, T=[T;Tk]; end %#ok<AGROW>
end
assert(height(T)>0,'Local result files contain no data rows.');
ids=sort(T.box_id(:));
unique_ids=unique(ids);
id_coverage_complete=isnumeric(ids) && numel(ids)==expected_top_level_boxes && ...
    all(isfinite(ids)) && all(ids==floor(ids)) && ...
    isequal(unique_ids,(1:expected_top_level_boxes)');
worker_ids=zeros(numel(files),1);
for k=1:numel(files)
    token=regexp(files(k).name,'^res_(\d+)\.csv$','tokens','once');
    assert(~isempty(token),'Unexpected local result filename: %s',files(k).name);
    worker_ids(k)=str2double(token{1});
end
if nargin<2 || isempty(expected_worker_count)
    expected_worker_count=max(worker_ids);
end
assert(isnumeric(expected_worker_count) && isscalar(expected_worker_count) && ...
    isfinite(expected_worker_count) && expected_worker_count>=1 && ...
    expected_worker_count==floor(expected_worker_count), ...
    'expected_worker_count must be a positive integer.');
expected_worker_ids=(1:expected_worker_count)';
done=dir(fullfile(results_dir,'done_*.txt')); done_ids=nan(numel(done),1);
for k=1:numel(done)
    token=regexp(done(k).name,'^done_(\d+)\.txt$','tokens','once');
    if ~isempty(token), done_ids(k)=str2double(token{1}); end
end
done_complete=isequal(sort(worker_ids),expected_worker_ids) && ...
    isequal(sort(done_ids),expected_worker_ids);
[current_provenance_present,current_provenance_valid,run_metadata]= ...
    validate_local_metadata(results_dir,expected_worker_ids, ...
    expected_worker_count,face_subdivisions,expected_top_level_boxes);
[minS,iS]=min(T.inf_S); [minL1,iL1]=min(T.lambda1_lower);
[maxL2,iL2]=max(T.lambda2_upper); maxDepth=max(T.max_subdivision_depth);
legacy_verified=all(T.ok==1) && minS>0 && id_coverage_complete && done_complete;
table3_fields={'mass_matrix_lower','lambda3_lower','lambda3_minus_3pi2_over2_lower'};
table3_fields_present=all(ismember(table3_fields,T.Properties.VariableNames));
minMass=nan; minMassBox=nan; minL3=nan; minL3Box=nan; minL3Gap=nan; minL3GapBox=nan;
if table3_fields_present
    [minMass,iMass]=min(T.mass_matrix_lower); minMassBox=T.box_id(iMass);
    [minL3,iL3]=min(T.lambda3_lower); minL3Box=T.box_id(iL3);
    [minL3Gap,iL3Gap]=min(T.lambda3_minus_3pi2_over2_lower);
    minL3GapBox=T.box_id(iL3Gap);
end
certificate_bounds_verified=legacy_verified && table3_fields_present && ...
    minL1>0 && minMass>0 && minL3>16 && minL3Gap>0;
verified=certificate_bounds_verified && current_provenance_valid;
summary=struct('verified',verified, ...
    'legacy_certificate_verified',legacy_verified, ...
    'certificate_bounds_verified',certificate_bounds_verified, ...
    'current_provenance_present',current_provenance_present, ...
    'current_provenance_valid',current_provenance_valid, ...
    'run_metadata',run_metadata, ...
    'table3_fields_present',table3_fields_present, ...
    'result_files',numel(files),'top_level_boxes',height(T), ...
    'expected_top_level_boxes',expected_top_level_boxes, ...
    'expected_worker_count',expected_worker_count, ...
    'certified_boxes',sum(T.ok==1),'failures',sum(T.ok~=1), ...
    'id_coverage_complete',id_coverage_complete,'done_markers_complete',done_complete, ...
    'minimum_certified_lower_bound_for_S',minS,'minimum_S_box_id',T.box_id(iS), ...
    'maximum_subdivision_depth',maxDepth, ...
    'lambda1_lower_min',minL1,'lambda1_lower_min_box_id',T.box_id(iL1), ...
    'lambda2_upper_max',maxL2,'lambda2_upper_max_box_id',T.box_id(iL2), ...
    'mass_matrix_lower_min',minMass,'mass_matrix_lower_min_box_id',minMassBox, ...
    'lambda3_lower_min',minL3,'lambda3_lower_min_box_id',minL3Box, ...
    'lambda3_minus_3pi2_over2_lower_min',minL3Gap, ...
    'lambda3_gap_lower_min_box_id',minL3GapBox, ...
    'wall_time_seconds',max(T.elapsed_seconds));
if summary.verified
    fprintf(['SAVED RESULT CHECK PASSED: all rows pass their recorded checks; ' ...
        'the saved bounds have S(t,e)>0, lambda_1>0, M>0, and lambda_3>16.\n']);
elseif summary.certificate_bounds_verified && ~summary.current_provenance_present
    fprintf(['LEGACY RESULT PROVENANCE: all saved numerical bounds pass, but ' ...
        'per-worker source/dependency metadata is absent.\n']);
elseif summary.legacy_certificate_verified && ~summary.table3_fields_present
    fprintf(['STALE RESULT SCHEMA: the saved cover verifies the previous S/index-1 ' ...
        'certificate but predates the mass/index-3 output fields.\n']);
else
    fprintf('SAVED RESULT CHECK FAILED: failures=%d, min S=%.17g.\n', ...
        summary.failures,minS);
end
fprintf(['files=%d boxes=%d minS=%.17g depth=%d lambda1>=%.17g ' ...
    'lambda2<=%.17g mass>=%.17g lambda3>=%.17g\n'], ...
    summary.result_files,summary.top_level_boxes,minS,maxDepth,minL1,maxL2,minMass,minL3);
end

function [present,valid,first] = validate_local_metadata( ...
        results_dir,expected_worker_ids,worker_count,face_subdivisions,total_boxes)
files=dir(fullfile(results_dir,'meta_*.json'));
present=~isempty(files); valid=false; first=struct();
if ~present, return; end
metadata_ids=nan(numel(files),1); items=cell(numel(files),1);
required={'schema_version','worker_id','worker_count','face_subdivisions', ...
    'expected_top_level_boxes','source_commit','source_dirty', ...
    'source_code_sha256','veigs_commit','run_id','matlab_version', ...
    'matlab_release','intlab_start_sha256','intlab_tree_sha256', ...
    'result_sha256','done_sha256'};
for k=1:numel(files)
    token=regexp(files(k).name,'^meta_(\d+)\.json$','tokens','once');
    if isempty(token), return; end
    metadata_ids(k)=str2double(token{1});
    try
        items{k}=jsondecode(fileread(fullfile(files(k).folder,files(k).name)));
    catch
        return
    end
    if ~all(cellfun(@(name)isfield(items{k},name),required)), return; end
end
if ~isequal(sort(metadata_ids),expected_worker_ids), return; end
first=items{1};
expected_veigs_commit='6556d39a0d9819bb172d232062b698aa76e420f6';
valid=has_valid_metadata_types(first) && first.schema_version==1 && ...
    ischar(first.source_commit) && ...
    ~isempty(regexp(first.source_commit,'^[0-9a-f]{40}$','once')) && ...
    ~logical(first.source_dirty) && ...
    ischar(first.source_code_sha256) && ...
    ~isempty(regexp(first.source_code_sha256,'^[0-9a-f]{64}$','once')) && ...
    strcmp(first.veigs_commit,expected_veigs_commit) && ...
    ischar(first.run_id) && ...
    ~isempty(regexp(first.run_id,'^[A-Za-z0-9._-]+$','once')) && ...
    ischar(first.intlab_start_sha256) && ...
    ~isempty(regexp(first.intlab_start_sha256,'^[0-9a-f]{64}$','once')) && ...
    ischar(first.intlab_tree_sha256) && ...
    ~isempty(regexp(first.intlab_tree_sha256,'^[0-9a-f]{64}$','once')) && ...
    ischar(first.result_sha256) && ...
    ~isempty(regexp(first.result_sha256,'^[0-9a-f]{64}$','once')) && ...
    ischar(first.done_sha256) && ...
    ~isempty(regexp(first.done_sha256,'^[0-9a-f]{64}$','once'));
if ~valid, return; end
runtime=qn_runtime_provenance();
repo_root=fileparts(fileparts(mfilename('fullpath')));
try
    recorded_source_sha256=qn_source_code_sha256( ...
        repo_root,first.source_commit);
catch
    valid=false;
    return
end
% The checked-in result commit necessarily postdates the compute commit.
% Bind to that recorded commit's executable tree, while allowing a current
% checkout that differs only in documentation or saved result artifacts.
valid=~runtime.source_dirty && ...
    strcmp(first.source_code_sha256,runtime.source_code_sha256) && ...
    strcmp(first.source_code_sha256,recorded_source_sha256);
if ~valid, return; end
for k=1:numel(items)
    item=items{k};
    if ~has_valid_metadata_types(item), valid=false; return; end
    result_path=fullfile(results_dir,sprintf('res_%03d.csv',metadata_ids(k)));
    done_path=fullfile(results_dir,sprintf('done_%03d.txt',metadata_ids(k)));
    try
        result_sha256=qn_sha256_file(result_path);
        done_sha256=qn_sha256_file(done_path);
    catch
        valid=false;
        return
    end
    valid=valid && item.schema_version==1 && ...
        item.worker_id==metadata_ids(k) && item.worker_count==worker_count && ...
        item.face_subdivisions==face_subdivisions && ...
        item.expected_top_level_boxes==total_boxes && ...
        strcmp(item.source_commit,first.source_commit) && ...
        ~logical(item.source_dirty) && ...
        strcmp(item.source_code_sha256,first.source_code_sha256) && ...
        strcmp(item.veigs_commit,first.veigs_commit) && ...
        strcmp(item.run_id,first.run_id) && ...
        strcmp(item.matlab_version,first.matlab_version) && ...
        strcmp(item.matlab_release,first.matlab_release) && ...
        strcmp(item.intlab_start_sha256,first.intlab_start_sha256) && ...
        strcmp(item.intlab_tree_sha256,first.intlab_tree_sha256) && ...
        strcmp(item.result_sha256,result_sha256) && ...
        strcmp(item.done_sha256,done_sha256);
    if ~valid, return; end
end
end

function tf=has_valid_metadata_types(item)
tf=isstruct(item) && isscalar(item) && ...
    isnumeric(item.schema_version) && isscalar(item.schema_version) && ...
    isnumeric(item.worker_id) && isscalar(item.worker_id) && ...
    isnumeric(item.worker_count) && isscalar(item.worker_count) && ...
    isnumeric(item.face_subdivisions) && isscalar(item.face_subdivisions) && ...
    isnumeric(item.expected_top_level_boxes) && ...
    isscalar(item.expected_top_level_boxes) && ...
    (islogical(item.source_dirty) || isnumeric(item.source_dirty)) && ...
    isscalar(item.source_dirty) && ...
    ischar(item.source_commit) && ischar(item.source_code_sha256) && ...
    ischar(item.veigs_commit) && ischar(item.run_id) && ...
    ischar(item.matlab_version) && ~isempty(item.matlab_version) && ...
    ischar(item.matlab_release) && ~isempty(item.matlab_release) && ...
    ischar(item.intlab_start_sha256) && ischar(item.intlab_tree_sha256) && ...
    ischar(item.result_sha256) && ischar(item.done_sha256);
end
