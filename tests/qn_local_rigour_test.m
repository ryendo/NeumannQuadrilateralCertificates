function report = qn_local_rigour_test(repo_root)
% Focused regression test for Algorithm 1 in Appendix A.4.
% Requires MATLAB and INTLAB; it does not run the full S^3 cover.

if nargin<1, repo_root=fileparts(fileparts(mfilename('fullpath'))); end
addpath(fullfile(repo_root,'src'));

PI=intval('pi');
rho=intval(3232)/(intval(27)*PI^6);
tmax=intval(sup(rho))*intval('1.000000000001');
grid=tmax*(intval([0 2 4 6 8 10 12 14 15 16])/intval(16));
face_box=[1 1 -0.01 0.01 -0.01 0.01 -0.01 0.01];
res=qn_single_box_certificate(face_box,grid);
assert(all([res.ok]),'Representative box was not certified by Algorithm 1.');
assert(all([res.S_before_exact_refinement]>0), ...
    'Representative box fails even before the exact root refinement.');
assert(all([res.infS]>=[res.S_before_exact_refinement]), ...
    'The intersection with (38)--(39) unexpectedly weakened the S bound.');
assert(all([res.exact_refinement_used]), ...
    'The refinement in (38)--(39) was not exercised by the test.');
assert(all(arrayfun(@(r) any(r.veigs_indices==1) && any(r.veigs_indices==3),res)), ...
    'The representative box was not certified by veigs for indices 1 and 3.');
assert(min([res.mass_lower])>0, ...
    'The representative box has no positive Gershgorin mass bound.');
assert(min(arrayfun(@(r) r.lam3(1),res))>16 && min([res.lambda3_gap_lower])>0, ...
    'The representative box does not certify lambda_3>16.');

report=struct('ok',all([res.ok]),'infS',min([res.infS]), ...
    'S_before_exact_refinement',min([res.S_before_exact_refinement]), ...
    'exact_refinement_gain',min([res.exact_refinement_gain]), ...
    'mass_lower',min([res.mass_lower]), ...
    'lambda3',min(arrayfun(@(r) r.lam3(1),res)), ...
    'lambda3_gap_lower',min([res.lambda3_gap_lower]));
fprintf(['LOCAL RIGOUR OK: S before (38)--(39)=%.17g refined S=%.17g gain=%.17g ' ...
    'mass>=%.17g lambda3>=%.17g\n'],report.S_before_exact_refinement, ...
    report.infS,report.exact_refinement_gain,report.mass_lower,report.lambda3);
end
